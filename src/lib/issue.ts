/**
 * The pasteable GitHub issue.
 *
 * Lives here rather than in the route so it can be unit-tested, and so the "Copy as issue"
 * button and the `?format=md` endpoint are guaranteed to produce identical text.
 */

import type { Hunt } from "@/lib/types";
import { edgeCaveat } from "@/lib/verdicts";

/**
 * The pasteable issue.
 *
 * Every number here comes from the hunt record, and the evidence trail is included so the
 * maintainer receiving it can audit the conclusion rather than take it on faith.
 */
export function renderIssue(hunt: Hunt): string {
  const report = hunt.report;
  if (!report) return "";

  const verdicts = hunt.probes
    .filter((p) => p.verdict !== null)
    .sort((a, b) => a.commitIndex - b.commitIndex)
    .map(
      (p) =>
        `| \`${p.commitSha.slice(0, 10)}\` | ${p.round} | ${p.verdict} | ${
          p.durationMs === null ? "—" : `${(p.durationMs / 1000).toFixed(1)}s`
        } | \`${p.jobId ?? "—"}\` |`,
    );

  const lines = [
    `### Regression bisected to \`${report.culpritSha.slice(0, 10)}\``,
    "",
    `**Commit:** \`${report.culpritSha}\``,
    `**Author:** ${report.culpritAuthor}`,
    `**Date:** ${report.culpritDate}`,
    `**Subject:** ${report.culpritSubject}`,
    "",
    `**Failing test:** \`${hunt.testCommand}\``,
    `**Range searched:** ${hunt.commits.length} commits from \`${hunt.goodRef}\` to \`${hunt.badRef}\``,
    `**Rounds:** ${hunt.round} · **Probes run:** ${hunt.probes.length}`,
    "",
  ];

  const caveat = edgeCaveat(
    hunt.commits,
    hunt.commits.find((c) => c.sha === report.culpritSha)?.index ?? null,
  );
  if (caveat) {
    lines.push(`> **Worth knowing.** ${caveat}`, "");
  }

  if (report.rootCauseMd) {
    lines.push(
      "#### Why it breaks",
      "",
      report.rootCauseMd,
      "",
      `<sub>Explanation generated by ${report.modelId}. The guilty commit above was established by running the test, not by a model.</sub>`,
      "",
    );
  } else if (report.narrationError) {
    lines.push(
      "#### Why it breaks",
      "",
      "_No generated explanation is attached to this report._",
      "",
    );
  }

  lines.push(
    "<details><summary>Evidence trail — every probe that produced this conclusion</summary>",
    "",
    "| Commit | Round | Verdict | Duration | Nebius job |",
    "|---|---|---|---|---|",
    ...verdicts,
    "",
    "</details>",
    "",
    "<sub>Bisected with Faultline across parallel Nebius Serverless AI Jobs.</sub>",
  );

  return lines.join("\n");
}
