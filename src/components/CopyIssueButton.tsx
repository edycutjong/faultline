"use client";

/**
 * `Copy as GitHub issue` — the memorable moment.
 *
 * One click yields a complete, pasteable issue built only from data the hunt actually
 * produced. The button morphs to "✓ Copied" for 2s (--dur-copy) and back.
 */

import { useCallback, useEffect, useRef, useState } from "react";
import type { Hunt } from "@/lib/types";
import { EM_DASH, formatCost, formatDuration, shortSha } from "./format";

export function buildIssueMarkdown(hunt: Hunt): string {
  const report = hunt.report;
  const rounds = hunt.probes.reduce((max, p) => Math.max(max, p.round), 0);
  const lines: string[] = [];

  const title = report
    ? `\`${shortSha(report.culpritSha)}\` breaks \`${hunt.testCommand}\``
    : `Bisection of \`${hunt.testCommand}\` did not name a culprit`;

  lines.push(`# ${title}`, "");
  lines.push(
    `Faultline bisected ${hunt.repoUrl} between \`${hunt.goodRef}\` and \`${hunt.badRef}\` — ` +
      `${hunt.commits.length} commits, ${hunt.probes.length} parallel probes, ${rounds} rounds.`,
    "",
  );

  lines.push("## Failing test", "", "```", hunt.testCommand, "```", "");

  if (report) {
    lines.push("## Culprit", "");
    lines.push(`- **Commit:** \`${report.culpritSha}\``);
    lines.push(`- **Subject:** ${report.culpritSubject}`);
    lines.push(`- **Author:** ${report.culpritAuthor}`);
    lines.push(`- **Date:** ${report.culpritDate || EM_DASH}`);
    lines.push("");

    lines.push("## Why it breaks", "");
    if (report.rootCauseMd) {
      lines.push(report.rootCauseMd.trim(), "");
      lines.push(
        `_Explanation generated by ${report.modelId}. The culprit above is verified by ` +
          `executed tests; this paragraph is not — read the diff before acting on it._`,
        "",
      );
    } else {
      lines.push(
        report.narrationError
          ? `_No explanation was generated: ${report.narrationError}_`
          : `_Explanation from ${report.modelId} is not available for this hunt._`,
        "",
      );
    }

    if (report.diffText.trim()) {
      lines.push("## Diff", "", "```diff", report.diffText.trim(), "```", "");
    }
  } else if (hunt.inconclusive) {
    lines.push("## No culprit named", "");
    lines.push(`**${hunt.inconclusive.headline}**`, "");
    lines.push(hunt.inconclusive.explanation, "");
  }

  lines.push("## Evidence", "");
  lines.push("| Round | Commit | Nebius job ID | Duration | Verdict |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const probe of [...hunt.probes].sort(
    (a, b) => a.round - b.round || a.commitIndex - b.commitIndex,
  )) {
    lines.push(
      `| ${probe.round} | \`${shortSha(probe.commitSha)}\` | \`${probe.jobId ?? EM_DASH}\` | ` +
        `${formatDuration(probe.durationMs)} | ${probe.verdict ?? "running"} |`,
    );
  }
  lines.push("");

  lines.push(
    `<sub>Hunt \`${hunt.id}\` · every probe ran as a Nebius Serverless AI Job · ` +
      `compute cost ${formatCost(hunt.costUsd)} · generated by Faultline.</sub>`,
  );

  return lines.join("\n");
}

async function writeToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // fall through to the textarea path below
  }
  try {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(area);
    return ok;
  } catch {
    return false;
  }
}

export function CopyIssueButton({ hunt }: { hunt: Hunt }) {
  const [state, setState] = useState<"idle" | "copied" | "failed">("idle");
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => () => {
    if (timer.current) clearTimeout(timer.current);
  }, []);

  const onClick = useCallback(async () => {
    const ok = await writeToClipboard(buildIssueMarkdown(hunt));
    setState(ok ? "copied" : "failed");
    if (timer.current) clearTimeout(timer.current);
    timer.current = setTimeout(() => setState("idle"), 2000);
  }, [hunt]);

  return (
    <div className="flex flex-col items-start gap-2">
      <button
        type="button"
        onClick={onClick}
        className={`rounded-lg border px-4 py-2.5 text-[14px] font-medium transition-colors duration-150 ${
          state === "copied"
            ? "copied-flash border-innocent"
            : "border-line bg-surface text-text hover:border-muted"
        }`}
      >
        {state === "copied" ? "✓ Copied" : state === "failed" ? "Copy blocked — select below" : "Copy as GitHub issue"}
      </button>
      <span aria-live="polite" className="sr-only">
        {state === "copied" ? "Issue markdown copied to clipboard" : ""}
      </span>
      {state === "failed" ? (
        <textarea
          readOnly
          rows={8}
          className="w-full rounded-lg border border-line bg-surface p-3 font-mono text-[12px] text-muted"
          value={buildIssueMarkdown(hunt)}
        />
      ) : null}
    </div>
  );
}
