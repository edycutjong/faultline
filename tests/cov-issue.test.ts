import { describe, it, expect } from "vitest";
import { renderIssue } from "@/lib/issue";
import type { Hunt, Probe } from "@/lib/types";
import { probe as baseProbe } from "./helpers";

function mkProbe(index: number, o: Partial<Probe> = {}): Probe {
  return baseProbe(index, "pass", { commitSha: `${index}`.padEnd(40, "a"), ...o });
}

function mkHunt(o: Partial<Hunt> = {}, report: Partial<NonNullable<Hunt["report"]>> | null = {}): Hunt {
  return {
    id: "h",
    repoUrl: "https://github.com/x/y",
    testCommand: "pytest",
    goodRef: "v1",
    goodSha: "g".repeat(40),
    badRef: "HEAD",
    installCommand: "pip install .",
    status: "done",
    commits: [],
    probes: [],
    round: 1,
    lowIndex: 0,
    highIndex: 1,
    report:
      report === null
        ? null
        : {
            culpritSha: "abcdef0123456789abcdef",
            culpritSubject: "subj",
            culpritAuthor: "Dana",
            culpritDate: "2026-08-05",
            diffText: "",
            rootCauseMd: null,
            modelId: "m-1",
            narrationProvider: null,
            narrationRequestId: null,
            narrationError: null,
            ...report,
          },
    inconclusive: null,
    pause: null,
    ...o,
  } as Hunt;
}

describe("renderIssue edge cases", () => {
  it("returns empty string without a report", () => {
    expect(renderIssue(mkHunt({}, null))).toBe("");
  });

  it("renders roles, skip, null duration/job, ordering, and omits unfinished probes", () => {
    const out = renderIssue(
      mkHunt({
        installCommand: "",
        probes: [
          mkProbe(3, { role: "bad", verdict: "error", durationMs: null, jobId: null }),
          mkProbe(1, { role: "good", verdict: "pass", durationMs: 1500, jobId: "job-1" }),
          mkProbe(2, { role: "interior", verdict: "fail", durationMs: 2000, jobId: "job-2" }),
          mkProbe(4, { verdict: null }),
        ],
      }),
    );
    expect(out).toContain("`detected from each commit`");
    expect(out).toContain("(known good) | 1 | pass | 1.5s | `job-1` |");
    expect(out).toContain("| 1 | fail | 2.0s | `job-2` |");
    expect(out).toContain("(failing ref) | 1 | skip | — | `—` |");
    expect(out.indexOf("job-1")).toBeLessThan(out.indexOf("job-2"));
    expect(out.indexOf("job-2")).toBeLessThan(out.indexOf("(failing ref)"));
    expect(out).not.toContain(`${4}`.padEnd(10, "a"));
    expect(out).not.toContain("Why it breaks");
  });

  it("includes root cause paragraph when present", () => {
    const out = renderIssue(mkHunt({}, { rootCauseMd: "Because X.", narrationError: "ignored" }));
    expect(out).toContain("Because X.");
    expect(out).toContain("Explanation generated by m-1");
    expect(out).not.toContain("No generated explanation");
  });

  it("notes missing explanation when narration failed", () => {
    const out = renderIssue(mkHunt({}, { narrationError: "boom" }));
    expect(out).toContain("_No generated explanation is attached to this report._");
  });
});
