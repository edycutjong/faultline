#!/usr/bin/env node
/**
 * Embed probe/probe.py into the app as a string module.
 *
 * Probes run on a stock `python:3.11` image and receive probe.py as an injected file at job
 * creation, so the deployed app must carry the script's exact bytes. `probe/` is excluded from
 * the Vercel deploy; this generated module is what ships. `tests/probe-source.test.ts` fails
 * if the two ever drift, so editing probe.py without re-running this is caught in CI.
 *
 *   node scripts/embed-probe.mjs
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(path.join(root, "probe", "probe.py"), "utf8");
const sha256 = createHash("sha256").update(source, "utf8").digest("hex");

const out = `// Generated by scripts/embed-probe.mjs from probe/probe.py — do not edit by hand.
// Re-run \`node scripts/embed-probe.mjs\` after changing the probe.

/** probe.py, byte for byte. Injected into every probe job as a file. */
export const PROBE_SOURCE: string = ${JSON.stringify(source)};

/** sha256 of PROBE_SOURCE, recorded on every probe so a verdict names the code that produced it. */
export const PROBE_SHA256 = "${sha256}";
`;

writeFileSync(path.join(root, "src", "lib", "probe-source.ts"), out);
console.log(`embedded probe.py (${Buffer.byteLength(source)} bytes, sha256 ${sha256.slice(0, 12)})`);
